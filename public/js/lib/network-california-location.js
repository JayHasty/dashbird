/**
 * @param {string | null | undefined} s
 * @returns {string}
 */
export function normalizeCaliforniaPlace(s) {
  return String(s || '')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\bst\.?\b/g, 'saint')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

const CALIFORNIA_CITY_KEYS = new Set(CALIFORNIA_CITY_NAMES.map((n) => normalizeCaliforniaPlace(n)));

const OTHER_STATE_ABBREV =
  /,\s*(AL|AK|AZ|AR|CO|CT|DC|DE|FL|GA|HI|ID|IL|IN|IA|KS|KY|LA|ME|MD|MA|MI|MN|MS|MO|MT|NE|NV|NH|NJ|NM|NY|NC|ND|OH|OK|OR|PA|RI|SC|SD|TN|TX|UT|VT|VA|WA|WV|WI|WY)\.?\b/i;

const OTHER_STATE_NAME =
  /,\s*(alabama|alaska|arizona|arkansas|colorado|connecticut|delaware|florida|georgia|hawaii|idaho|illinois|indiana|iowa|kansas|kentucky|louisiana|maine|maryland|massachusetts|michigan|minnesota|mississippi|missouri|montana|nebraska|nevada|new hampshire|new jersey|new mexico|new york|north carolina|north dakota|ohio|oklahoma|oregon|pennsylvania|rhode island|south carolina|south dakota|tennessee|texas|utah|vermont|virginia|washington|west virginia|wisconsin|wyoming|district of columbia)\b/i;

const CA_STATE_MARKER = /,\s*(ca|calif\.?|california)\b|\bcalifornia\b/i;

/**
 * True when a contact location is a California city/region (or explicitly CA).
 * Explicit other-state suffixes (e.g. ", NY") win over bare city-name matches.
 * @param {string | null | undefined} location
 * @returns {boolean}
 */
export function isCaliforniaLocation(location) {
  const raw = String(location || '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!raw) return false;
  const lower = raw.toLowerCase();
  if (lower === 'out of town' || lower === 'delta' || lower === 'remote' || lower === 'online') {
    return false;
  }
  const hasOtherState = OTHER_STATE_ABBREV.test(raw) || OTHER_STATE_NAME.test(raw);
  const hasCaState = CA_STATE_MARKER.test(raw) || /^(ca|calif\.?)$/i.test(raw);
  if (hasOtherState && !hasCaState) return false;
  if (hasCaState) return true;

  const cityPart = raw.split(',')[0] || raw;
  const cityLower = cityPart.toLowerCase();
  if (cityLower === 'sf' || cityLower === 'san fran') return true;
  if (cityLower === 'la' || cityLower === 'l.a.' || cityLower === 'l.a') return true;
  const n = normalizeCaliforniaPlace(cityPart);
  if (!n) return false;
  return CALIFORNIA_CITY_KEYS.has(n);
}

/**
 * California cities first (A→Z), then everywhere else (A→Z).
 * @param {string} a
 * @param {string} b
 * @returns {number}
 */
export function compareContactLocationLabels(a, b) {
  const aCa = isCaliforniaLocation(a);
  const bCa = isCaliforniaLocation(b);
  if (aCa !== bCa) return aCa ? -1 : 1;
  return String(a).localeCompare(String(b), undefined, { sensitivity: 'base' });
}
